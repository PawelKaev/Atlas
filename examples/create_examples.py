# create_examples.py
import os

files = {}

files['привет.at'] = '''функция приветствие(имя: Строка): Строка:
    "Привет, " ++ имя ++ "!"

функция главная():
    пусть сообщение = приветствие("Мир")
    написать(сообщение)
    пусть x = 42
    пусть y = 10
    написать(x + y)
    если x > y:
        написать("x больше")
    иначе:
        написать("y больше или равны")
    пусть изм счётчик = 0
    пока счётчик < 3:
        написать(счётчик)
        счётчик += 1
    написать("Готово!")
'''

files['арифм.at'] = '''функция главная():
    пусть a = 10
    пусть b = 3
    написать(a + b)
    написать(a - b)
    написать(a * b)
'''

files['loop.at'] = '''функция главная():
    пусть изм счётчик = 0
    пока счётчик < 5:
        написать(счётчик)
        счётчик += 1
'''

files['struct.at'] = '''структура Точка:
    x: Целое
    y: Целое

функция главная():
    пусть p = Точка { x: 10, y: 20 }
    написать(p.x)
    написать(p.y)
'''

os.makedirs('examples', exist_ok=True)
for name, content in files.items():
    path = os.path.join('examples', name)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f'Создан {path}')
